#!/usr/bin/env python3
"""
Convert a simple DOT file (generated by our mindmap scripts) to a basic SVG tree layout.
This is a lightweight renderer that does not require Graphviz; it parses nodes/edges
and lays them out left-to-right by depth.
"""
import os
import re
import sys
from collections import defaultdict, deque

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DOT_PATH = os.path.join(ROOT, "experiments", "mindmaps", "llamole_gbm_mindmap_en.dot")
SVG_PATH = os.path.join(ROOT, "experiments", "mindmaps", "llamole_gbm_mindmap_en.svg")


def parse_dot(dot_path):
    nodes = {}
    edges = []
    node_re = re.compile(r'(\w+)\s*\[label="(.*)"\];')
    edge_re = re.compile(r'(\w+)\s*->\s*(\w+);')
    with open(dot_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            m = node_re.match(line)
            if m:
                nid = m.group(1)
                label = m.group(2)
                nodes[nid] = label
                continue
            m2 = edge_re.match(line)
            if m2:
                a, b = m2.group(1), m2.group(2)
                edges.append((a, b))
    return nodes, edges


def compute_depths(nodes, edges):
    children = defaultdict(list)
    parents = defaultdict(list)
    for a, b in edges:
        children[a].append(b)
        parents[b].append(a)
    # roots: nodes without parents
    roots = [n for n in nodes.keys() if n not in parents]
    if not roots:
        # fallback: choose first node as root
        roots = [next(iter(nodes.keys()))]
    depth = {}
    q = deque()
    for r in roots:
        depth[r] = 0
        q.append(r)
    while q:
        u = q.popleft()
        for v in children.get(u, []):
            nd = depth.get(v, None)
            if nd is None or nd > depth[u] + 1:
                depth[v] = depth[u] + 1
                q.append(v)
    # nodes not reached: assign max depth +1
    maxd = max(depth.values()) if depth else 0
    for n in nodes.keys():
        if n not in depth:
            maxd += 1
            depth[n] = maxd
    return depth, children


def wrap_label(text, max_chars=30):
    if len(text) <= max_chars:
        return [text]
    # try to break at spaces, otherwise break by characters
    parts = []
    cur = ""
    for token in re.split(r'(\s+)', text):
        if len(cur) + len(token) <= max_chars:
            cur += token
        else:
            if cur:
                parts.append(cur.strip())
            tok = token.strip()
            while len(tok) > max_chars:
                parts.append(tok[:max_chars])
                tok = tok[max_chars:]
            cur = tok
    if cur:
        parts.append(cur.strip())
    return parts


def estimate_text_size(lines, char_w=7, line_h=14, padding=8):
    width = max(len(line) for line in lines) * char_w + padding * 2
    height = len(lines) * line_h + padding * 2
    return width, height


def generate_svg(nodes, edges, depth, children, svg_path):
    # group by depth
    by_depth = defaultdict(list)
    for n, d in depth.items():
        by_depth[d].append(n)
    max_depth = max(by_depth.keys())
    # layout parameters
    x_gap = 280
    y_gap = 120
    margin = 20
    # compute node sizes and positions
    node_boxes = {}
    depth_heights = {}
    for d, node_list in by_depth.items():
        heights = []
        widths = []
        for n in node_list:
            lines = wrap_label(nodes[n], max_chars=36)
            w, h = estimate_text_size(lines)
            node_boxes[n] = {"lines": lines, "w": w, "h": h}
            heights.append(h)
            widths.append(w)
        depth_heights[d] = max(heights) if heights else 0
    # canvas size
    width = (max_depth + 1) * x_gap + margin * 2
    max_nodes_in_depth = max(len(v) for v in by_depth.values()) if by_depth else 1
    height = max_nodes_in_depth * y_gap + margin * 2 + 100
    # assign positions: x by depth, y spaced within depth
    positions = {}
    for d, node_list in by_depth.items():
        count = len(node_list)
        total_h = (count - 1) * y_gap
        start_y = (height - total_h) / 2
        for i, n in enumerate(node_list):
            x = margin + d * x_gap
            y = start_y + i * y_gap
            positions[n] = (x, y)
    # write SVG
    with open(svg_path, "w", encoding="utf-8") as f:
        f.write(f'<?xml version="1.0" encoding="UTF-8"?>\n')
        f.write(f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}">\n')
        # defs
        f.write('<defs>\n')
        f.write('<style type="text/css"><![CDATA[\n')
        f.write('  .node { fill: #f7f7f7; stroke: #2b6cb0; stroke-width:1.2 }\n')
        f.write('  .label { font-family: Helvetica, Arial, sans-serif; font-size:12px; fill:#111 }\n')
        f.write('  .edge { stroke:#444; stroke-width:1.0; fill:none }\n')
        f.write(']]></style>\n')
        f.write('</defs>\n')
        # edges
        for a, b in edges:
            if a in positions and b in positions:
                ax, ay = positions[a]
                bx, by = positions[b]
                axc = ax + node_boxes[a]["w"] + 10
                ayc = ay + node_boxes[a]["h"] / 2
                bxc = bx - 10
                byc = by + node_boxes[b]["h"] / 2
                # simple polyline: axc,ayc -> midx,ayc -> midx,byc -> bxc,byc
                midx = (axc + bxc) / 2
                f.write(f'<path class="edge" d="M {axc} {ayc} C {midx} {ayc} {midx} {byc} {bxc} {byc}" />\n')
        # nodes
        for n, (x, y) in positions.items():
            box = node_boxes[n]
            w = box["w"]
            h = box["h"]
            rx = 6
            f.write(f'<g>\n')
            f.write(f'  <rect class="node" x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" ry="{rx}" />\n')
            # text
            lines = box["lines"]
            text_x = x + 8
            text_y = y + 16
            for i, line in enumerate(lines):
                ly = text_y + i * 14
                safe = line.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                f.write(f'  <text class="label" x="{text_x}" y="{ly}">{safe}</text>\n')
            f.write('</g>\n')
        f.write('</svg>\n')
    print("SVG written to:", svg_path)


def main():
    if not os.path.exists(DOT_PATH):
        print("DOT file not found:", DOT_PATH)
        sys.exit(1)
    nodes, edges = parse_dot(DOT_PATH)
    if not nodes:
        print("No nodes parsed from DOT.")
        sys.exit(1)
    depth, children = compute_depths(nodes, edges)
    generate_svg(nodes, edges, depth, children, SVG_PATH)


if __name__ == "__main__":
    main()


